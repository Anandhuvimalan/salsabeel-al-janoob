-- Initial schema for the Salsabeel Al Janoob site.
-- Recreated from the original project's data and the app's queries.
--
-- Access model:
--   * Site content tables: anyone can read, signed-in admins can write.
--   * Form tables (contact, newsletter, job applications): anyone can insert,
--     only signed-in admins can read/update/delete.
--   * Storage buckets are public-read; signed-in admins can write. Visitors can
--     upload résumés to the "applications" bucket.

