-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  -- Public-read content tables, admin-write
  foreach t in array array[
    'hero_sections', 'features_section', 'about_section', 'services_section', 'process_section',
    'whatwedo_section', 'testimonials_section', 'faqs_section', 'footer_section',
    'aboutpage_hero', 'aboutpage_company', 'aboutpage_values', 'aboutpage_visionmission',
    'aboutpage_leadership', 'aboutpage_testimonials', 'aboutpage_memorial', 'aboutpage_calltoaction',
    'allwaste', 'chemicalwaste', 'civil', 'drug', 'education', 'language', 'laundry', 'marriage',
    'retail', 'vasthu', 'job_categories', 'experience_ranges', 'jobs'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "Public read" on public.%I for select using (true)', t);
    execute format('create policy "Admins write" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;

  -- Form tables: anyone can submit, only admins can see/manage
  foreach t in array array['applications', 'contact_submissions', 'newsletter_subscribers'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "Anyone can submit" on public.%I for insert to anon, authenticated with check (true)', t);
    execute format('create policy "Admins manage" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

