insert into storage.buckets (id, name, public)
select b, b, true
from unnest(array[
  'hero-images', 'feature-icons', 'about-section-images', 'services-images', 'process-icons',
  'whatwedo-icons', 'testimonial-images', 'footer-images',
  'aboutpage-hero-images', 'aboutpage-company-images', 'aboutpage-values-icons',
  'aboutpage-visionmission-icons', 'aboutpage-leadership-images', 'aboutpage-testimonials-images',
  'aboutpage-memorial-images',
  'allwaste-images', 'chemicalwaste-images', 'civil-images', 'drug-images', 'education-images',
  'language-images', 'laundry-images', 'marriage-images', 'retail-images', 'vasthu-images',
  -- Résumés: public because the app stores and opens them via public URLs
  'applications'
]) as b
on conflict (id) do nothing;

create policy "Public read site files" on storage.objects
  for select using (bucket_id in (select id from storage.buckets where public and id <> 'applications'));

create policy "Admins manage files" on storage.objects
  for all to authenticated using (true) with check (true);

create policy "Anyone can upload a resume" on storage.objects
  for insert to anon with check (bucket_id = 'applications');

-- ---------------------------------------------------------------------------
-- Helper used once after importing data with explicit ids: moves every identity
-- sequence past the current max(id) so new inserts don't collide.
-- ---------------------------------------------------------------------------
create or replace function public.reset_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
begin
  for r in
    select c.table_name
    from information_schema.columns c
    where c.table_schema = 'public' and c.column_name = 'id' and c.is_identity = 'YES'
  loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
      'public.' || r.table_name, r.table_name
    );
  end loop;
end $$;

revoke all on function public.reset_identity_sequences() from public, anon, authenticated;
grant execute on function public.reset_identity_sequences() to service_role;
